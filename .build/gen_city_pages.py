def slice_between(src, start, end, label):
    i = src.find(start)
    if i == -1:
        raise SystemExit("Could not find start of %s in the parent page" % label)
    j = src.find(end, i)
    if j == -1:
        raise SystemExit("Could not find end of %s in the parent page" % label)
    return src[i:j + len(end)]


