def patch_parent(src):
    block = areas_block()
    if AREAS_START in src and AREAS_END in src:
        i = src.index(AREAS_START)
        j = src.index(AREAS_END) + len(AREAS_END)
        return src[:i] + block + src[j:]
    anchor = '  <section class="cta-band">'
    if anchor not in src:
        raise SystemExit("Could not find the CTA band to insert the areas block before")
    return src.replace(anchor, block + "\n" + anchor, 1)


def patch_sitemap(path):
    with open(path, encoding="utf-8") as fh:
        xml = fh.read()
    entries = []
    for c in CITIES:
        loc = "%s/services/screw-piling-%s.html" % (BASE, c["slug"])
        if loc in xml:
            continue
        entries.append(
            "  <url>\n    <loc>%s</loc>\n    <lastmod>%s</lastmod>\n"
            "    <changefreq>monthly</changefreq>\n    <priority>0.8</priority>\n  </url>"
            % (loc, TODAY))
    if not entries:
        return 0
    xml = xml.replace("</urlset>", "\n".join(entries) + "\n</urlset>")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(xml)
    return len(entries)


